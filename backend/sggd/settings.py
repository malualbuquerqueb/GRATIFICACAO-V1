def _carregar_env(caminho):
    """Carrega o arquivo .env (CHAVE=valor) sem sobrescrever variáveis já definidas."""
    if not caminho.exists():
        return
    for linha in caminho.read_text(encoding="utf-8").splitlines():
        linha = linha.strip()
        if linha and not linha.startswith("#") and "=" in linha:
            chave, valor = linha.split("=", 1)
            os.environ.setdefault(chave.strip(), valor.strip())


def _obrigatoria(nome):
    try:
        return os.environ[nome]
    except KeyError:
        raise ImproperlyConfigured(
            f"Defina a variável de ambiente {nome} (veja backend/.env.example)."
        ) from None

def _bool_env(nome, padrao=False):
    valor = os.environ.get(nome)
    if valor is None:
        return padrao
    return valor.lower() in ("1", "true", "yes", "on")


def _lista_env(nome, padrao=""):
    return [
        item.strip()
        for item in os.environ.get(nome, padrao).split(",")
        if item.strip()
    ]


